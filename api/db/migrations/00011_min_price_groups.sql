-- Правило — одна полоса крепости одной редакции. abv_from — «свыше», abv_to — «до … включительно»
-- (пусто — без верхней границы). Для другого объёма цена пересчитывается пропорционально
-- эталонному; same_price_over_ml — тара свыше этого объёма и до эталонного стоит как эталонная
-- (у водки 0,375–0,5 л).
create table min_retail_prices (
    id                 uuid primary key default uuidv7(),
    group_code         text not null references min_price_groups (code),
    valid_from         date not null,
    abv_from           numeric(4, 1) not null default 0 check (abv_from >= 0 and abv_from < 100),
    abv_to             numeric(4, 1) check (abv_to > abv_from and abv_to <= 100),
    price              numeric(12, 2) not null check (price > 0),
    volume_ml          integer not null default 500 check (volume_ml > 0),
    same_price_over_ml integer check (same_price_over_ml > 0),
    source             text not null,
    unique (group_code, valid_from, abv_from)
);

