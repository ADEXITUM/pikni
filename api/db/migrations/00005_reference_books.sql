-- Регионы происхождения: Шампань, Коньяк, Кахетия, Спейсайд.
create table origin_regions (
    id           uuid primary key default uuidv7(),
    country_code text not null references countries (code),
    name         text not null,
    is_active    boolean not null default true,
    unique (country_code, name)
);

create table producers (
    id           uuid primary key default uuidv7(),
    name         text not null unique,
    inn          text check (inn ~ '^([0-9]{10}|[0-9]{12})$'),
    country_code text not null references countries (code),
    is_active    boolean not null default true
);

create table brands (
    id          uuid primary key default uuidv7(),
    producer_id uuid not null references producers (id),
    name        text not null,
    is_active   boolean not null default true,
    unique (producer_id, name)
);

-- Объёмы тары в миллилитрах: точное целое, «0,5 л» — только отображение.
create table volumes (
    ml        integer primary key check (ml between 10 and 30000),
    is_active boolean not null default true
);

