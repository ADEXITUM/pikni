-- Виды алкогольной продукции по классификатору видов и кодов НСИ ЕГАИС: с 2021 года
-- к трёхзначным кодам добавлены четырёх- и пятизначные подкоды. marked — помарочный учёт
-- (федеральные специальные марки), quantity — без марок: пиво, пивные напитки, сидр,
-- пуаре и медовуха (171-ФЗ, ст. 12), их маркирует «Честный знак».
create table product_kinds (
    code             text primary key check (code ~ '^[0-9]{3,5}$'),
    name             text not null,
    egais_accounting text not null check (egais_accounting in ('marked', 'quantity'))
);

-- Причины списания сети и тип списания в акте ЕГАИС, которому каждая соответствует.
create table writeoff_reasons (
    id         uuid primary key default uuidv7(),
    name       text not null unique,
    egais_type text not null,
    is_active  boolean not null default true
);

